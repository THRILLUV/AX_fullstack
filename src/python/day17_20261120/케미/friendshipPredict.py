from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error

# ----------------------------------------
# 1. 조원들이 조사한 데이터 12개
# ----------------------------------------

# 힌트(X)
# [대화 시간(분), 공통 관심사(개), 흡연 취향 일치(0/1), 개인 만남(회)]

힌트 = [
    [45, 1, 0, 0],
    [61, 1, 1, 0],
    [30, 0, 1, 0],
    [70, 2, 0, 0],
    [15, 1, 0, 0],
    [15, 1, 0, 0],
    [60, 1, 1, 0],
    [60, 0, 0, 0],
    [70, 0, 1, 0],
    [40, 0, 1, 0],
    [50, 0, 0, 0],
    [70, 0, 1, 0]
]

# 정답(y)
# 각 평가자가 상대방에게 준 친밀도 점수

친밀도 = [
    52, 64, 34, 50,
    30, 30, 70, 60,
    80, 30, 37, 65
]

# ----------------------------------------
# 2. 베이스라인
# ----------------------------------------

평균 = sum(친밀도[:10]) / 10

기준선예측 = [평균, 평균]

print(
    "베이스라인 평균 오차:",
    round(
        mean_absolute_error(
            친밀도[10:],
            기준선예측
        ), 1
    )
)

# ----------------------------------------
# 3. 다중회귀 학습 및 시험
# ----------------------------------------

모델 = LinearRegression()

# 앞의 10개 데이터로 학습
모델.fit(힌트[:10], 친밀도[:10])

# 뒤의 2개 데이터 예측
예측 = 모델.predict(힌트[10:])

print("정답:", 친밀도[10:])
print("예측:", 예측.round(1))

print(
    "평균 오차:",
    round(
        mean_absolute_error(친밀도[10:], 예측), 1
    )
)

print("coef_:", 모델.coef_.round(2))
print("절편:", round(모델.intercept_, 2))

# ----------------------------------------
# 4. 전체 데이터로 다시 학습
# ----------------------------------------

# Streamlit에서는 전체 12개를 학습한 모델 사용
모델.fit(힌트, 친밀도)

# ----------------------------------------
# 5. 새로운 조건으로 친밀도 예측
# ----------------------------------------

def 친밀도예측(대화시간, 관심사, 흡연값, 만남횟수):

    새로운힌트 = [[
        대화시간,
        관심사,
        흡연값,
        만남횟수
    ]]

    예측 = 모델.predict(새로운힌트)[0]

    # 0~100점 범위로 제한
    점수 = max(0, min(100, float(예측)))

    return 점수


# 참고:
# 개인 만남 횟수는 학습 데이터에서 0이지만 일단 오류나 예외로 빼야되는걸로 잡고 싶었음.