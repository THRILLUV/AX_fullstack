def 등급(점수):
    if 점수 >= 90:
        if 점수 >= 95:
            print("+")
        print("1등급")
        
    elif 점수 >= 80:
        print("2등급")
    elif 점수 >= 70:
        print("3등급")
    elif 점수 >= 60:
        print("4등급")
    else:
        print("5등급")



