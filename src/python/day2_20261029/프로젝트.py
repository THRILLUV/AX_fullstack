# 다이어트 할 때에 금일 칼로리 계산기 
# 기초 대사량 먼저 구하기
print("기초대사량을 먼저 구하겠습니다!")
cm = int(input("키를 입력하세요: "))
kg = int(input("몸무게를 입력하세요: "))
age = int(input("나이를 입력하세요: "))
남여 = int(input("남자라면 0 여자분이시면 1을 기재해주세요!"))
기초대사량 = (10 * kg) + (6.25 * cm) - (5 * age) + 5 - (남여 * 166)
print("현재 본인의 대략적인 기초대사량은", 기초대사량 , "입니다!")
print("이제부터 다이어트 시 오늘 남은 칼로리를 계산해보겠습니다!")
print("저희처럼 하루종일 앉아있으면 기초대사량에 1.2배? 정도밖에 못태웁니다!")
kcal = int(input("금일 먹은 칼로리를 기재해주세요: "))
남은칼로리 = (기초대사량 * 1.2) // 1 - kcal
print("현재 남은 칼로리는", 남은칼로리, "입니다!")
a = ""
if 기초대사량 < kcal:
    a = "이미 글렀네요.."
elif 남은칼로리 >= 1000:
    a = "집가서 야식 먹어도 괜찮겠네여!"
elif 남은칼로리 <1000 and 남은칼로리 >= 600:
    a = "일반식 먹으시면 됩니다!"
elif 남은칼로리 < 600 and 남은칼로리 >= 300:
    a = "조금만 먹으세요..."
elif 남은칼로리 <300 and 남은칼로리 >= 0:
    a = "닭가슴살 한개 먹고 물 많이 마셔봐요.."
print(a)
print("근육량과 활동량 등으로 인해 실제와 다를 수 있습니다!")