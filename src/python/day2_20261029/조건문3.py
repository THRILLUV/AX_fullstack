# 4 . 커피 사면 사이즈 선택 (결과)

while True:
    사이즈 = input("사이즈 선택(S/M/L)").replace(" ", "")
    
    if 사이즈 in ("S", "s"):
        결과 = "3000원"
    
    elif 사이즈 in ("M", "m"):
        결과 = "4000원"
        
    elif 사이즈 in ("L", "l"):
        결과 = "5000원"

    else:
        결과 = "그런 사이즈는 없다! 다시쳐라!"
       
       
    print(결과)