# 회사 출근 확인 앱
# 회사에서 오늘 출근한 직원들의 이름을 리스트에 저장했습니다.

# ["민수", "지영", "철수", "수빈", "영희"]

# 관리자는 특정 직원이 출근했는지 확인하고 싶습니다.

#1. 앱이 저장해 둔것은?
#   ㄴ 순서대로 출근한 오늘 출근 리스트
출근명단 = ["민수", "지영", "철수", "수빈", "영희"]

# 2.앱이 하는 일을 순서대로 작성?
#   ㄴ 1) 출근한 직원의 이름을 리스트에 저장한다 (순서대로)
#   ㄴ 2) 관리자 검색 - // 인풋 - 이름을 입력하세요 검색 이름 받기
#   ㄴ 3) "이름" in 출근명단 에 있다면
#   ㄴ 4) 입력된 이름이 리스트에 있는지 index로 리스트 검색
#   ㄴ 5) 출근 순서대로 순서 = 출근명단.index(검색)<된이름 + 1 해서 
#   ㄴ 6) 프린트로 순서, "번째 출근" 출력
#   ㄴ 7) 이름이 없으면 else 로 없음 출력)

# 3.몇번째 값을 꺼내나?/어디서부터 어디까지 짜르나?
#   ㄴ 리스트 안에 있으면 통과
# 중복되지 않은 값


# 출근 = input("출근부 출첵: ")
# 명단추가 = 출근
이름 = input("출근을 확인할 이름을 입력하세요: ")

if 이름 in 출근명단:
    순서 = 출근명단.index(이름) + 1
    print(순서, "번째로 출근! 했습니다!")
    # print(출근명단.index(이름) + 1 )
else:
    print("출근 안함")
