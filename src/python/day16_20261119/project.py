# 2. 정답에 진짜 힌트가 2개 이상 들어가나요? (무엇에 얼마를 곱해 더하나요?)
#    예: 물 개수 × 1,000원 + 과자 개수 × 1,500원

# 3. 정답 계산에 필요 없는 "숫자" 힌트 2개는 무엇인가요?
