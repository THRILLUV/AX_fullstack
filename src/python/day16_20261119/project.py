# 4. 입력과 정답이 들어간 표를 10줄 이상 만들 수 있나요?
#    정답에 작은 덤(잡음)을 더해서, 딱 맞아떨어지지 않게 만드세요.
#    앞 7줄은 공부용, 뒤 3줄은 시험용입니다.

# 5. 개인정보 없이 만들었나요?
